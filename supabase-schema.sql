create table if not exists public.orders (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  customer_email text not null,
  customer_name text,
  address text,
  city text,
  postal_code text,
  items jsonb not null,
  total numeric(10, 2) not null,
  status text not null default 'confirmed'
);

create table if not exists public.newsletter_subscribers (
  id bigint generated by default as identity primary key,
  email text unique not null,
  created_at timestamptz not null default now()
);

alter table public.newsletter_subscribers enable row level security;
grant usage on schema public to public;
grant insert on public.newsletter_subscribers to public;
drop policy if exists "Allow newsletter signups" on public.newsletter_subscribers;
create policy "Allow newsletter signups" on public.newsletter_subscribers
  for insert to public with check (true);
